#!/usr/bin/env python3
"""Generate ``cases.json`` - the replayable input corpus.

Run from the repository root::

    python tools/make_cases.py

The generator is deterministic (no clock, no randomness), so the checked-in
``cases.json`` can be regenerated byte-for-byte and reviewed in a diff.
Every case is a self-contained scenario; the README maps each one to the
requirement it demonstrates.
"""

from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "cases.json")


_LABELS = {}


def labelled(step, label=None):
    """Attach a stable human-readable label used by the README/tests."""
    if label is not None:
        step["label"] = label
    return step


def setup(processes=("p1",), resources=(("r1", "t1", None),), clock=1000):
    steps = [{"op": "set_clock", "now_ms": clock}]
    for name in processes:
        steps.append({"op": "create_process", "process": name})
    for name, tenant, rights in resources:
        step = {"op": "create_resource", "resource": name, "tenant": tenant}
        if rights is not None:
            step["rights"] = rights
        steps.append(step)
    return steps


def cases():
    out = []

    # -- 1. basic allow / deny on a single handle -------------------------
    steps = setup()
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 1, "method": "list"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read",
         "resource": "r1", "tenant": "t1"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read",
         "resource": "r1", "tenant": "other"},
    ]
    out.append({"case_id": "01_basic_allow_deny", "steps": steps})

    # -- 2. transitive attenuation: child may only narrow -----------------
    steps = setup(processes=("p1", "p2"))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write", "list"]},
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 4, "rights": ["read", "write"]},
        {"op": "transfer", "parent": {"process": "p2", "handle": 4,
                                      "generation": 1},
         "to_process": "p1", "handle": 9, "rights": ["read"]},
        {"op": "check", "process": "p2", "handle": 4, "method": "write"},
        {"op": "check", "process": "p2", "handle": 4, "method": "list"},
        {"op": "check", "process": "p1", "handle": 9, "method": "read"},
        {"op": "check", "process": "p1", "handle": 9, "method": "write"},
        # escalation attempt must be rejected
        {"op": "transfer", "parent": {"process": "p1", "handle": 9},
         "to_process": "p2", "handle": 12, "rights": ["read", "write"]},
        # window widening attempt must be rejected
        {"op": "transfer", "parent": {"process": "p1", "handle": 9},
         "to_process": "p2", "handle": 13, "rights": ["read"],
         "not_after": 99999999999},
        # narrowing the window is fine
        {"op": "transfer", "parent": {"process": "p1", "handle": 9},
         "to_process": "p2", "handle": 14, "rights": ["read"],
         "not_after": 1500},
        {"op": "check", "process": "p2", "handle": 14, "method": "read"},
        {"op": "set_clock", "now_ms": 1600},
        {"op": "check", "process": "p2", "handle": 14, "method": "read"},
    ]
    out.append({"case_id": "02_transfer_attenuation", "steps": steps})

    # -- 3. multiple sandboxes: every one must allow ----------------------
    steps = setup()
    steps += [
        {"op": "create_sandbox", "sandbox": "sb_ro", "rights": ["read", "list"]},
        {"op": "create_sandbox", "sandbox": "sb_nolist", "rights": ["read", "write"]},
        {"op": "create_sandbox", "sandbox": "sb_all", "rights": ["read", "write", "list"]},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write", "list"],
         "sandboxes": ["sb_ro", "sb_all"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 1, "method": "list"},
        {"op": "tighten_sandbox", "sandbox": "sb_all", "rights": ["read", "write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "list"},
        # removing "read" too leaves the handle with nothing this sandbox allows
        {"op": "tighten_sandbox", "sandbox": "sb_all", "rights": ["write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 1, "method": "list"},
        # adding a right back is not a tightening
        {"op": "tighten_sandbox", "sandbox": "sb_all", "rights": ["read", "write"]},
    ]
    out.append({"case_id": "03_multi_sandbox_intersection", "steps": steps})

    # -- 4. process restart invalidates descendants -----------------------
    steps = setup(processes=("p1", "p2"))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 2, "rights": ["read"]},
        {"op": "check", "process": "p2", "handle": 2, "method": "read"},
        {"op": "restart_process", "process": "p1"},
        {"op": "check", "process": "p2", "handle": 2, "method": "read"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        # transfer refused from an ancestor of a dead session
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 3, "rights": ["read"]},
    ]
    out.append({"case_id": "04_restart_invalidates_descendants", "steps": steps})

    # -- 5. resource rebuild invalidates --------------------------------
    steps = setup()
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "rebuild_resource", "resource": "r1"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        # a fresh grant sees the new generation
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read",
         "generation": 1},
    ]
    out.append({"case_id": "05_resource_rebuild", "steps": steps})

    # -- 6. handle-number recycling and same-number generations ---------
    steps = setup()
    steps += [
        {"op": "grant", "process": "p1", "handle": 7, "resource": "r1",
         "rights": ["read"]},
        {"op": "grant", "process": "p1", "handle": 7, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "list_slot", "process": "p1", "handle": 7},
        # old generation is superseded, not silently upgraded
        {"op": "check", "process": "p1", "handle": 7, "method": "write",
         "generation": 1},
        {"op": "check", "process": "p1", "handle": 7, "method": "write",
         "generation": 2},
        # explicitly asking for a generation older than the slot max fails
        {"op": "grant", "process": "p1", "handle": 7, "resource": "r1",
         "rights": ["read"], "generation": 1},
        {"op": "grant", "process": "p1", "handle": 7, "resource": "r1",
         "rights": ["read"], "generation": 9},
        {"op": "list_slot", "process": "p1", "handle": 7},
    ]
    out.append({"case_id": "06_handle_number_reuse", "steps": steps})

    # -- 7. revoking a parent kills descendants, exact generation --------
    steps = setup(processes=("p1", "p2", "p3"))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write", "list"]},
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 2, "rights": ["read", "write"]},
        {"op": "transfer", "parent": {"process": "p2", "handle": 2},
         "to_process": "p3", "handle": 3, "rights": ["read"]},
        {"op": "check", "process": "p3", "handle": 3, "method": "read"},
        {"op": "revoke", "process": "p2", "handle": 2},
        # child of the revoked handle is blocked, and the report names the
        # revoked ancestor with its exact generation
        {"op": "check", "process": "p3", "handle": 3, "method": "read"},
        {"op": "handle_info", "process": "p3", "handle": 3},
        # the revoked handle itself
        {"op": "check", "process": "p2", "handle": 2, "method": "read"},
        # sibling branch under p1 is unaffected
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 5, "rights": ["read"]},
        {"op": "check", "process": "p2", "handle": 5, "method": "read"},
    ]
    out.append({"case_id": "07_parent_revoke", "steps": steps})

    # -- 8. re-granting the same rights does not resurrect an old generation
    steps = setup()
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "revoke", "process": "p1", "handle": 1},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        # identical rights, same handle number, new generation
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "read",
         "generation": 1},
        {"op": "check", "process": "p1", "handle": 1, "method": "read",
         "generation": 2},
        {"op": "list_slot", "process": "p1", "handle": 1},
    ]
    out.append({"case_id": "08_regrant_does_not_revive", "steps": steps})

    # -- 9. protected multi-resource op, all-or-nothing receipt ----------
    steps = setup(resources=(("r1", "t1", None), ("r2", "t1", None),
                             ("r3", "t1", None)))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "grant", "process": "p1", "handle": 2, "resource": "r2",
         "rights": ["read", "write"]},
        {"op": "grant", "process": "p1", "handle": 3, "resource": "r3",
         "rights": ["read", "write"]},
        {"op": "protected_io", "op_id": "txn-001", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1", "payload": "a"},
             {"handle": 2, "method": "write", "resource": "r2", "payload": "b"},
             {"handle": 3, "method": "write", "resource": "r3", "payload": "c"},
         ]},
        # duplicate op id returns the first committed result
        {"op": "protected_io", "op_id": "txn-001", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1", "payload": "a"},
             {"handle": 2, "method": "write", "resource": "r2", "payload": "b"},
             {"handle": 3, "method": "write", "resource": "r3", "payload": "c"},
         ]},
        # one revoked right aborts the whole thing, no partial I/O
        {"op": "revoke", "process": "p1", "handle": 2},
        {"op": "protected_io", "op_id": "txn-002", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1", "payload": "a"},
             {"handle": 2, "method": "write", "resource": "r2", "payload": "b"},
             {"handle": 3, "method": "write", "resource": "r3", "payload": "c"},
         ]},
        # best_effort writes only what is allowed, and still needs a receipt
        {"op": "protected_io", "op_id": "txn-003", "process": "p1",
         "mode": "best_effort",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1", "payload": "a"},
             {"handle": 2, "method": "write", "resource": "r2", "payload": "b"},
         ]},
        {"op": "io_audit"},
    ]
    out.append({"case_id": "09_protected_io_modes", "steps": steps})

    # -- 10. precheck snapshot: detachable but rechecked at use ----------
    steps = setup(resources=(("r1", "t1", None), ("r2", "t1", None)))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "grant", "process": "p1", "handle": 2, "resource": "r2",
         "rights": ["read", "write"]},
        {"op": "precheck", "process": "p1", "handle": 1, "method": "write",
         "ttl_ms": 500},
        # after the precheck the resource is rebuilt: the snapshot is
        # structurally fine but its resource generation is stale
        {"op": "rebuild_resource", "resource": "r1"},
        {"op": "set_clock", "now_ms": 1100},
        {"op": "protected_io", "op_id": "txn-010", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1",
              "payload": "late", "precheck": "P0001"},
         ]},
        # re-grant at the new resource generation, then precheck afresh
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "precheck", "process": "p1", "handle": 1, "method": "write",
         "ttl_ms": 500},
        {"op": "protected_io", "op_id": "txn-011", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1",
              "payload": "ok", "precheck": "P0002"},
         ]},
        # reusing the consumed token is refused, never re-authorized
        {"op": "protected_io", "op_id": "txn-012", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1",
              "payload": "again", "precheck": "P0002"},
         ]},
        # an unused precheck left lying around until it expires
        {"op": "precheck", "process": "p1", "handle": 2, "method": "write",
         "ttl_ms": 100},
        {"op": "set_clock", "now_ms": 1300},
        {"op": "protected_io", "op_id": "txn-013", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 2, "method": "write", "resource": "r2",
              "payload": "expired", "precheck": "P0003"},
         ]},
        # an unknown token cannot be trusted
        {"op": "protected_io", "op_id": "txn-014", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 2, "method": "write", "resource": "r2",
              "payload": "never", "precheck": "P9999"},
         ]},
        # a precheck issued for "read" cannot authorize a "write"
        {"op": "precheck", "process": "p1", "handle": 2, "method": "read",
         "ttl_ms": 500},
        {"op": "protected_io", "op_id": "txn-015", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 2, "method": "write", "resource": "r2",
              "payload": "swapped", "precheck": "P0004"},
         ]},
        {"op": "io_audit"},
    ]
    out.append({"case_id": "10_precheck_staleness", "steps": steps})

    # -- 11. ancestor keeps read but loses write ------------------------
    steps = setup(processes=("p1", "p2"))
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"]},
        {"op": "transfer", "parent": {"process": "p1", "handle": 1},
         "to_process": "p2", "handle": 2, "rights": ["read"]},
        # p2 asks for read: fine.  p2 asks for write: ancestor never held it.
        {"op": "check", "process": "p2", "handle": 2, "method": "read"},
        # transfer from p2 to p3 asking for write
        {"op": "create_process", "process": "p3"},
        {"op": "transfer", "parent": {"process": "p2", "handle": 2},
         "to_process": "p3", "handle": 3, "rights": ["read", "write"]},
        {"op": "transfer", "parent": {"process": "p2", "handle": 2},
         "to_process": "p3", "handle": 3, "rights": ["read"]},
        {"op": "check", "process": "p3", "handle": 3, "method": "write"},
        {"op": "check", "process": "p3", "handle": 3, "method": "read"},
    ]
    out.append({"case_id": "11_rights_exchange", "steps": steps})

    # -- 12. read/write swap between two handles -----------------------
    steps = setup()
    steps += [
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read"]},
        {"op": "grant", "process": "p1", "handle": 2, "resource": "r1",
         "rights": ["write"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 2, "method": "read"},
        {"op": "revoke", "process": "p1", "handle": 1},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["write"], "generation": 3},
        # now handle 1 (gen 3) writes and handle 2 writes; neither reads
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "check", "process": "p1", "handle": 2, "method": "write"},
        {"op": "protected_io", "op_id": "txn-012", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 1, "method": "write", "resource": "r1", "payload": "one"},
             {"handle": 2, "method": "write", "resource": "r1", "payload": "two"},
         ]},
        # same consumption id with the opposite rights, after a rebuild
        {"op": "rebuild_resource", "resource": "r1"},
        {"op": "protected_io", "op_id": "txn-012", "process": "p1",
         "mode": "all_or_nothing",
         "items": [
             {"handle": 2, "method": "write", "resource": "r1", "payload": "two"},
             {"handle": 1, "method": "write", "resource": "r1", "payload": "one"},
         ]},
    ]
    out.append({"case_id": "12_read_write_swap", "steps": steps})

    # -- 13. sandbox tightening after grant blocks existing handles -----
    steps = setup()
    steps += [
        {"op": "create_sandbox", "sandbox": "sb", "rights": ["read", "write"]},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["read", "write"], "sandboxes": ["sb"]},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "tighten_sandbox", "sandbox": "sb", "rights": []},
        {"op": "check", "process": "p1", "handle": 1, "method": "write"},
        {"op": "check", "process": "p1", "handle": 1, "method": "read"},
        {"op": "handle_info", "process": "p1", "handle": 1},
    ]
    out.append({"case_id": "13_sandbox_tightening", "steps": steps})

    # -- 14. error handling and rejected requests ----------------------
    steps = setup()
    steps += [
        {"op": "check", "process": "nobody", "handle": 1, "method": "read"},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "missing",
         "rights": ["read"]},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["write"], "sandboxes": ["nope"]},
        {"op": "set_clock", "now_ms": 999},
        {"op": "grant", "process": "p1", "handle": 1, "resource": "r1",
         "rights": ["fly"]},
        {"op": "create_process", "process": "p1"},
        {"op": "revoke", "process": "p1", "handle": 44},
        {"op": "protected_io", "op_id": "bad", "process": "p1",
         "mode": "nope", "items": [{"handle": 1, "method": "read"}]},
        {"op": "protected_io", "op_id": "bad2", "process": "p1",
         "items": []},
        {"op": "no_such_op"},
    ]
    out.append({"case_id": "14_error_codes", "steps": steps})

    # Give every step a stable label: the case id, the index, and the op.
    # The CLI echoes the label, so README tables and tests can address a step
    # without hard-coding an array position.
    for case in out:
        for index, step in enumerate(case["steps"]):
            step["label"] = "%s#%02d" % (case["case_id"].split("_")[0], index)
    return out


def main():
    doc = {
        "format": "sandbox-cases/1",
        "description": (
            "Replayable capability-check scenarios. Every step is offline and "
            "deterministic; see README for the mapping from case to rule."
        ),
        "cases": cases(),
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print("wrote %s (%d cases)" % (OUT, len(doc["cases"])))


if __name__ == "__main__":
    main()
